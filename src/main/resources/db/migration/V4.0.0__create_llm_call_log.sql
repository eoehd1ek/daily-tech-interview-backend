CREATE TABLE llm_call_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purpose VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    question_id BIGINT,
    evaluation_attempt_id BIGINT,
    provider VARCHAR(255) NOT NULL,
    requested_model VARCHAR(255) NOT NULL,
    response_model VARCHAR(255),
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    duration_ms BIGINT,
    response_id VARCHAR(255),
    finish_reason VARCHAR(255),
    request_messages TEXT NOT NULL,
    request_options TEXT NOT NULL,
    response_data TEXT,
    input_tokens BIGINT,
    output_tokens BIGINT,
    total_tokens BIGINT,
    cached_input_tokens BIGINT,
    reasoning_tokens BIGINT,
    failure_stage VARCHAR(255),
    error_data TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_llm_call_log_started_at_id ON llm_call_log (started_at DESC, id DESC);
CREATE INDEX idx_llm_call_log_evaluation_attempt_id ON llm_call_log (evaluation_attempt_id);
